# Builds .private-words.txt (git-ignored) for check-private.ps1 from THIS machine: names of your own folders
# (Desktop, Documents, Downloads, repos) and exact versions of installed apps. Review and edit the file afterwards:
# remove generic words that rules legitimately contain. (ASCII only: Windows PowerShell 5.1.)
$ErrorActionPreference = 'Stop'
Set-Location (git rev-parse --show-toplevel)

$words = [System.Collections.Generic.SortedSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
$generic = @('desktop', 'documents', 'downloads', 'music', 'videos', 'pictures', 'github', 'projects', 'source', 'repos',
             'temp', 'images', 'assets', 'build', 'builds', 'backup', 'archive', 'program', 'programs', 'games', 'steam',
             'unity', 'microsoft', 'windows', 'python', 'node', 'scripts', 'tools', 'notes', 'samples', 'models', 'data')

$generic += @('files', 'file', 'license', 'image', 'cursor', 'discord', 'compressed', 'video', 'audio', 'document',
              'visual studio', 'windowspowershell', 'powershell', 'settings', 'config', 'export', 'output', 'default')
# Only places that hold the user's own work: repos/projects and the Desktop. Documents and Downloads roots are full of
# app-created folders with generic names ("Visual Studio 2022", "Compressed"), which would only produce noise.
$roots = @([Environment]::GetFolderPath('Desktop'), (Join-Path $env:USERPROFILE 'source\repos'),
           (Join-Path ([Environment]::GetFolderPath('MyDocuments')) 'GitHub'))
foreach ($r in $roots) {
    if (-not (Test-Path -LiteralPath $r)) { continue }
    foreach ($i in Get-ChildItem -LiteralPath $r -Force -ErrorAction SilentlyContinue) {
        if ($i.Extension -in '.lnk', '.url', '.ini') { continue }  # shortcuts name apps, not the user's work
        $n = [IO.Path]::GetFileNameWithoutExtension($i.Name)
        $lower = $n.ToLowerInvariant()
        if ($n.Length -ge 5 -and -not ($generic | Where-Object { $lower -eq $_ -or $lower.StartsWith($_ + ' ') })) { [void]$words.Add($n) }
    }
}

# Top-level folders of other fixed drives (project and media folders often live there), minus system folders.
$system = @('$recycle.bin', 'system volume information', 'program files', 'program files (x86)', 'programdata',
            'windows', 'users', 'recovery', 'perflogs', 'msocache', 'config.msi', 'boot', 'intel', 'amd', 'nvidia',
            # default install roots and generic tool folders that rules legitimately name
            'riot games', 'steamlibrary', 'xboxgames', 'epic games', 'ea games', '.agent-tmp', 'msys64', 'cygwin64')
foreach ($d in [IO.DriveInfo]::GetDrives() | Where-Object { $_.DriveType -eq 'Fixed' -and $_.IsReady }) {
    foreach ($i in Get-ChildItem -LiteralPath $d.RootDirectory.FullName -Directory -Force -ErrorAction SilentlyContinue) {
        $lower = $i.Name.ToLowerInvariant()
        if ($i.Name.Length -ge 5 -and $system -notcontains $lower -and -not ($generic | Where-Object { $lower -eq $_ })) { [void]$words.Add($i.Name) }
    }
}

# Tools that aren't in the registry but print a version (their exact version fingerprints the machine).
foreach ($tool in 'claude', 'node', 'git') {
    try { $v = (& $tool --version 2>$null | Select-Object -First 1) -replace '^[^\d]*', '' -replace '\s.*$', ''; if ($v -match '^\d+\.\d+\.\d+') { [void]$words.Add($Matches[0]) } } catch { }
}

# Exact versions with 3+ parts (e.g. 1.2.3.4567) are what tie text to one machine; product names alone are not.
$keys = 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\*',
        'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\*',
        'HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\*'
foreach ($a in Get-ItemProperty $keys -ErrorAction SilentlyContinue) {
    $v = [string]$a.DisplayVersion
    if ($v -match '^\d+(\.\d+){2,}$' -and $v.Length -ge 6) { [void]$words.Add($v) }
}

$header = "# Generated by tools/make-private-words.ps1 on this machine. Git-ignored: never commit it.`n# One term per line. Remove anything generic that rules or docs legitimately use."
Set-Content -LiteralPath '.private-words.txt' -Value (@($header) + @($words)) -Encoding UTF8
Write-Host ".private-words.txt: $($words.Count) terms. Review it, then run tools/check-private.ps1 -All -Commits"
