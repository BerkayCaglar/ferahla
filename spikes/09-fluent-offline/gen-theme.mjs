// Turns the light/dark themes from @fluentui/tokens into static CSS. Run once during development;
// the output (fluent-theme.css) is committed, so the tokens package is never used at run time.
// Usage: node gen-theme.mjs <path to the tokens package's lib/index.js> <output.css>
import { pathToFileURL } from 'node:url';
import { writeFileSync } from 'node:fs';

const [, , tokensIndex, outFile] = process.argv;
const { webLightTheme, webDarkTheme } = await import(pathToFileURL(tokensIndex).href);

const decls = (theme, indent) =>
  Object.entries(theme).map(([k, v]) => `${indent}--${k}: ${v};`).join('\n');

const css = `/* Generated by gen-theme.mjs from @fluentui/tokens webLightTheme/webDarkTheme. Do not edit. */
:root {
  color-scheme: light;
${decls(webLightTheme, '  ')}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${decls(webDarkTheme, '    ')}
  }
}
:root[data-theme="dark"] {
  color-scheme: dark;
${decls(webDarkTheme, '  ')}
}
`;
writeFileSync(outFile, css);
console.log(`${Object.keys(webLightTheme).length} light / ${Object.keys(webDarkTheme).length} dark token → ${outFile}`);
